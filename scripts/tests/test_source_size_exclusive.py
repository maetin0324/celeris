"""Tests for `source-size-report.py --exclusive-classes` (health v2 B0).

Fixes the contract: every line of every tracked file lands in exactly one
class, the class totals equal the tracked total (checked against an
independent `git grep -c ''` count), and the gate's classification
(`source-size-report/1`, check-source-size.py) is untouched.
"""
import importlib.util
import io
import json
import os
import shutil
import subprocess
import sys
import tempfile
import textwrap
import unittest
from contextlib import redirect_stdout
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "scripts/dev/source-size-report.py"
CONFIG = REPO / "scripts/dev/source-size-report.toml"
spec = importlib.util.spec_from_file_location("source_size_report_exclusive", SOURCE)
ssr = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = ssr
spec.loader.exec_module(ssr)

CFG = ssr.load_exclusive_config(str(CONFIG), str(REPO))


def classes_of(path: str, content: str) -> dict:
    return ssr.classify_file_exclusive(CFG, path, content.encode())["classes"]


def only(path: str, content: str = "x\n") -> str:
    got = classes_of(path, content)
    assert len(got) == 1, got
    return next(iter(got))


def run_git(root, *args):
    return subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True, check=True).stdout


class InlineTestBoundaryTests(unittest.TestCase):
    def test_cfg_test_mod_lines_are_inline_test_and_the_rest_production(self):
        src = textwrap.dedent(
            """\
            pub fn add(a: i32, b: i32) -> i32 {
                a + b
            }

            #[cfg(test)]
            mod tests {
                #[test]
                fn adds() {
                    assert_eq!(super::add(1, 2), 3);
                }
            }
            pub fn after() {}
            """
        )
        # 12 lines: cfg attr through the mod's closing brace (lines 5-11) are test.
        self.assertEqual(classes_of("crates/x/src/lib.rs", src), {"production": 5, "inline_test": 7})

    def test_string_with_closing_brace_does_not_end_the_test_mod_early(self):
        src = 'fn a() {}\n#[cfg(test)]\nmod tests {\n    const S: &str = "\n}\n";\n}\nfn b() {}\n'
        self.assertEqual(classes_of("crates/x/src/lib.rs", src), {"production": 2, "inline_test": 6})

    def test_cfg_test_helper_outside_a_mod_is_inline_test(self):
        src = "fn a() {}\n#[cfg(test)]\nfn helper() {\n    a();\n}\n"
        self.assertEqual(classes_of("crates/x/src/lib.rs", src), {"production": 1, "inline_test": 4})

    def test_cfg_not_test_is_production(self):
        src = "#[cfg(not(test))]\nfn real() {\n}\n"
        self.assertEqual(classes_of("crates/x/src/lib.rs", src), {"production": 3})

    def test_external_test_file_is_not_split(self):
        src = "fn a() {}\n#[cfg(test)]\nmod t {\n}\n"
        self.assertEqual(classes_of("crates/x/src/foo/tests.rs", src), {"external_test": 4})
        self.assertEqual(classes_of("crates/x/tests/it.rs", src), {"external_test": 4})

    def test_inline_split_matches_the_gate_heuristic(self):
        rust = "fn a() {}\n#[cfg(test)]\nmod tests {\n    fn b() {}\n}\n"
        info = ssr.analyze_rust_file(ssr.split_lines(rust))
        self.assertEqual(classes_of("crates/x/src/lib.rs", rust),
                         {"production": info.prod_lines, "inline_test": info.inline_test_lines})


class GeneratedTests(unittest.TestCase):
    def test_generated_dir_and_gen_suffix(self):
        self.assertEqual(only("web/api/generated/types.ts"), "generated")
        self.assertEqual(only("web/routeTree.gen.ts"), "generated")

    def test_rust_module_named_generated_is_code(self):
        self.assertEqual(only("crates/task-dispatch/src/auto_resolve/generated/mod.rs", "fn a() {}\n"), "production")
        self.assertEqual(only("crates/task-dispatch/src/auto_resolve/generated/tests.rs"), "external_test")

    def test_marker_in_head_marks_generated(self):
        body = "// This file was automatically generated by a tool.\nexport const a = 1;\n"
        self.assertEqual(only("web/lib/thing.ts", body), "generated")
        self.assertEqual(only("crates/x/src/lib.rs", "// @generated\nfn a() {}\n"), "generated")

    def test_marker_after_head_window_is_ignored(self):
        body = "x\n" * CFG.marker_lines + "// @generated\n"
        self.assertEqual(only("web/lib/thing.ts", body), "production")

    def test_vendor_and_lockfile_win_over_marker(self):
        self.assertEqual(only("crates/script-runtime/vendor/deno_core/x.rs", "// DO NOT EDIT\n"), "vendor")
        self.assertEqual(only("Cargo.lock", "# @generated by cargo\n"), "lockfile")


