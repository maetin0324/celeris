class TotalsTests(unittest.TestCase):
    def setUp(self):
        self.root = Path(tempfile.mkdtemp(prefix="ssr-excl-"))
        self.addCleanup(shutil.rmtree, self.root, True)
        run_git(self.root, "init", "-q")
        run_git(self.root, "config", "user.email", "t@example.com")
        run_git(self.root, "config", "user.name", "T")
        files = {
            "crates/a/src/lib.rs": "fn a() {}\n#[cfg(test)]\nmod tests {\n    fn t() {}\n}\n",
            "crates/a/tests/it.rs": "fn it() {}\n",
            "crates/a/vendor/z/lib.rs": "pub fn z() {}\n",
            "crates/a/migrations/0001.sql": "CREATE TABLE t (x);\n",
            "web/api/generated/types.ts": "export type A = 1;\n",
            "web/x.ts": "export const x = 1",  # unterminated last line
            "tests/fixtures/f.json": "{}\n",
            "docs/a.md": "# a\n\nb\n",
            "scripts/dev/tool.sh": "#!/bin/sh\necho hi\n",
            "empty.txt": "",
            "Cargo.lock": "# lock\n",
            "odd.txt": "a\fb\x1cc\n",  # \f and \x1c are not line breaks here
        }
        for rel, content in files.items():
            p = self.root / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content)
        (self.root / "img.png").write_bytes(b"\x89PNG\0\n\n\n")
        os.symlink("docs/a.md", self.root / "link.md")
        run_git(self.root, "add", "-A")
        run_git(self.root, "commit", "-q", "-m", "s")
        shutil.copy(CONFIG, self.root / "cfg.toml")
        self.cfg = ssr.load_exclusive_config(str(self.root / "cfg.toml"), str(self.root))

    def independent_count(self) -> int:
        out = run_git(self.root, "grep", "-I", "-c", "", "HEAD")
        return sum(int(line.rsplit(":", 1)[1]) for line in out.splitlines() if line)

    def test_class_totals_equal_tracked_lines_for_rev_and_worktree(self):
        expected = self.independent_count()
        for rev in ("HEAD", None):
            r = ssr.run_exclusive_report(str(self.root), self.cfg, rev)
            t = r["totals"]
            self.assertTrue(t["consistent"])
            self.assertEqual(t["tracked_lines"], expected)
            self.assertEqual(sum(r["class_totals"].values()), expected)
            self.assertEqual(sum(r["language_totals"].values()), expected)
            cells = sum(c["lines"] for row in r["matrix"].values() for c in row.values())
            self.assertEqual(cells, expected)
            self.assertEqual(t["files"], 14)  # 12 text + png + symlink; untracked cfg.toml is not counted
            self.assertEqual(t["binary_or_symlink_files"], 2)
        self.assertEqual(r["class_totals"]["inline_test"], 4)
        self.assertEqual(r["class_totals"]["production"], 1 + 1 + 1)  # lib.rs prod, x.ts, odd.txt

    def test_rev_reads_the_commit_not_the_worktree(self):
        (self.root / "web/x.ts").write_text("a\nb\nc\nd\n")
        at_head = ssr.run_exclusive_report(str(self.root), self.cfg, "HEAD")
        worktree = ssr.run_exclusive_report(str(self.root), self.cfg, None)
        self.assertEqual(worktree["totals"]["tracked_lines"] - at_head["totals"]["tracked_lines"], 3)
        self.assertTrue(worktree["worktree_dirty"])
        self.assertIsNone(at_head["worktree_dirty"])

    def test_cli_json_has_sha_version_environment_and_views(self):
        buf = io.StringIO()
        with redirect_stdout(buf):
            code = ssr.main(["--root", str(self.root), "--config", str(self.root / "cfg.toml"),
                             "--format", "json", "--exclusive-classes", "--rev", "HEAD"])
        self.assertEqual(code, 0)
        r = json.loads(buf.getvalue())
        self.assertEqual(r["sha"], run_git(self.root, "rev-parse", "HEAD").strip())
        self.assertEqual(r["classification"], "source-size-exclusive/1")
        self.assertEqual(r["gate_classification"], "source-size-report/1")
        self.assertEqual(set(r["environment"]), {"host", "python", "platform", "git"})
        self.assertEqual(r["views"]["all_tracked"]["lines"], r["totals"]["tracked_lines"])
        self.assertEqual(set(r["classes"]), set(ssr.EXCLUSIVE_CLASSES))
        self.assertEqual(len(ssr.EXCLUSIVE_CLASSES), 12)

    def test_rev_without_exclusive_mode_is_a_usage_error(self):
        with self.assertRaises(SystemExit):
            with redirect_stdout(io.StringIO()):
                ssr.main(["--root", str(self.root), "--rev", "HEAD"])

    def test_config_rejects_unknown_class(self):
        bad = self.root / "bad.toml"
        bad.write_text('[exclusive_classes]\nversion = "v"\n[[exclusive_classes.rules]]\nclass = "code"\npath = "x"\n')
        with self.assertRaises(ValueError):
            ssr.load_exclusive_config(str(bad), str(self.root))


class RepoAndGateTests(unittest.TestCase):
    def test_this_repo_at_head_adds_up(self):
        r = ssr.run_exclusive_report(str(REPO), CFG, "HEAD")
        out = run_git(REPO, "grep", "-I", "-c", "", "HEAD")
        independent = sum(int(line.rsplit(":", 1)[1]) for line in out.splitlines() if line)
        self.assertTrue(r["totals"]["consistent"])
        self.assertEqual(r["totals"]["tracked_lines"], independent)

    def test_gate_config_is_unchanged_by_the_exclusive_section(self):
        prod, inline, exceptions = ssr.load_config(str(CONFIG), str(REPO))
        self.assertEqual((prod, inline), (2000, 300))
        self.assertEqual([e.path for e in exceptions], ["crates/task-api/src/types.rs"])
        baseline = json.loads((REPO / "scripts/dev/source-size-baseline.json").read_text())
        self.assertEqual(baseline["classification"], "source-size-report/1")


